API.RTL = RTL;
API.table = function (code) { return T[code] || T.en; };
API.has = function (code) { return Object.prototype.hasOwnProperty.call(T, code); };
API.dir = function (code) { return RTL[code] ? 'rtl' : 'ltr'; };
API.keys = function () { var out = [], k; for (k in EN) if (EN.hasOwnProperty(k)) out.push(k); return out; };
/* t('question_of', {i: 3, n: 10}, 'fr') -> "Question 3 / 10".
   An unknown key returns the key itself (loud in a test, harmless on screen) and a
   missing value falls back to English rather than to an empty line. */
API.t = function (key, vars, code) {
  var tab = T[code] || T.en;
  var s = tab[key];
  if (s == null) s = EN[key];
  if (s == null) return key;
  if (!vars) return s;
  return String(s).replace(/\{(\w+)\}/g, function (m, name) {
    return vars[name] == null ? m : String(vars[name]);
  });
};

