"""Vendor the SVG flags the map can use, and generate their stylesheet.

Source: https://github.com/lipis/flag-icons — MIT, (c) 2013 Panayiotis Lipiridis.
The flags themselves are the Wikipedia/ISO 3166 set, drawn as SVG.

WHY VENDORED AND NOT A CDN <link>
The app is a static page that must work served from a LAN box with no internet, and
its own ethos is "no libraries, no tiles". A <link> to jsDelivr would also make every
viewer's browser fetch a third-party asset, and would make the flags disappear in
exactly the offline case where the map itself still works.

WHAT IS COPIED
Every 4x3 flag the app can ask for, from three places: the ISO_A2 codes in the data
layers, the codes app.js maps to by hand (NE_ISO2: Natural Earth ships "-99" for 17
features - France and Germany are fine, France and Norway are not - and "CN-TW" style
sub-codes), and the 18 flags on the language chips. That is 242 files, 1.6 MB; a
browser fetches only the handful it paints, because each flag is a background-image.
The 1x1 (round) set is not copied - the CSS makes a circle out of the 4x3 one.

The two tables are READ OUT OF app.js rather than duplicated here: a code that is
mapped there but missing here is a flag that silently does not appear, which is
exactly the bug this comment replaced.

    python3 tools/fetch_flags.py <path-to-flag-icons-checkout>

The checkout is the release zip: https://github.com/lipis/flag-icons/archive/refs/tags/v7.6.0.zip
"""
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(HERE, 'data')

# a language chip needs a flag, and a language is not a country: these are the usual
# convention (the language's main country of origin). `en` -> gb rather than us, `pt`
# -> pt, `zh` -> cn. See the README for the caveat.
LANG_CODE = {
    'en': 'gb', 'fr': 'fr', 'de': 'de', 'es': 'es', 'pt': 'pt', 'nl': 'nl', 'sv': 'se',
    'ru': 'ru', 'uk': 'ua', 'el': 'gr', 'zh': 'cn', 'ja': 'jp', 'ko': 'kr', 'ar': 'sa',
    'fa': 'ir', 'he': 'il', 'hi': 'in', 'bn': 'bd',
}


def codes_from_app():
    """the two hand-written tables in app.js: NE_ISO2 (a feature -> flag code) and
    LANG_FLAG (a language -> flag code). Parsed rather than duplicated, so the two
    cannot drift."""
    src = open(os.path.join(HERE, 'app.js'), encoding='utf-8').read()
    out = set()
    for name in ('NE_ISO2', 'LANG_FLAG'):
        m = re.search(r'var %s = \{(.*?)\};' % name, src, re.S)
        if not m:
            sys.exit('could not find %s in app.js' % name)
        out.update(v.lower() for v in re.findall(r":\s*'([A-Za-z]{2})'", m.group(1)))
    return out


def codes_in_data():
    """every ISO 3166-1 alpha-2 the map can ask for: the layers, plus the tables"""
    out = set(LANG_CODE.values()) | codes_from_app()
    for name in ('so50.geojson', 'countries.geojson', 'ne10m.geojson'):
        p = os.path.join(DATA, name)
        if not os.path.exists(p):
            continue
        geo = json.load(open(p, encoding='utf-8'))
        for f in geo['features']:
            iso = (f['properties'].get('ISO_A2') or '')
            if re.match(r'^[A-Za-z]{2}$', iso):
                out.add(iso.lower())
            m = re.match(r'^([A-Za-z]{2})-', iso)      # e.g. CN-TW, FR-973
            if m:
                out.add(m.group(1).lower())
    return out


def main(src):
    flags = os.path.join(src, 'flags', '4x3')
    if not os.path.isdir(flags):
        sys.exit('no flags/4x3 in ' + src)
    outdir = os.path.join(DATA, 'flags')
    os.makedirs(outdir, exist_ok=True)
    codes = sorted(codes_in_data())
    copied, missing, total = [], [], 0
    for c in codes:
        p = os.path.join(flags, c + '.svg')
        if not os.path.exists(p):
            missing.append(c)
            continue
        dst = os.path.join(outdir, c + '.svg')
        shutil.copyfile(p, dst)
        copied.append(c)
        total += os.path.getsize(dst)
    # a stylesheet with one rule per flag we ship, in the same class names as the
    # library (.fi, .fi-fr) so a new flag can be dropped in without touching the CSS
    lines = [
        '/* SVG flags, vendored from https://github.com/lipis/flag-icons (MIT,',
        '   (c) 2013 Panayiotis Lipiridis). Generated by tools/fetch_flags.py - do not',
        '   edit by hand: re-run it to add a flag. Class names match the library, so',
        '   <span class="fi fi-fr"></span> is the whole API. */',
        '.fi{position:relative;display:inline-block;width:1.3333em;line-height:1em;'
        'background-size:contain;background-position:50%;background-repeat:no-repeat}',
        '.fi:before{content:"\\00a0"}',
        '.fi.fis{width:1em}',
    ]
    for c in copied:
        # flags.css sits at the repository root, beside style.css, so the URL is
        # relative to the ROOT - not to data/ (a ../ there climbs out of the site)
        lines.append('.fi-%s{background-image:url(data/flags/%s.svg)}' % (c, c))
    with open(os.path.join(HERE, 'flags.css'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print('flags: %d copied, %.2f MB' % (len(copied), total / 1048576.0))
    print('stylesheet: flags.css (%.1f kB)' % (os.path.getsize(os.path.join(HERE, 'flags.css')) / 1024.0))
    if missing:
        print('no flag shipped for: %s' % ' '.join(missing))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'flag-icons-7.6.0')
